function renderSidebar(groupKey, subKey) {
  if (typeof menuData === "undefined") return;
  const data = menuData[groupKey];
  if (!data) return;

  const titleElem = document.getElementById("sidebar-category-title");
  const subTabsContainer = document.getElementById("sub-tabs-container");
  const ul = document.getElementById("sidebar-dynamic-list");
  if (!ul) return;

  if (titleElem) titleElem.textContent = data.title;
  ul.innerHTML = "";

  if (data.hasSubTabs && subTabsContainer) {
    subTabsContainer.style.display = "block";
    subTabsContainer.innerHTML = "";

    if (!subKey || !data.subTabs[subKey]) {
      subKey = Object.keys(data.subTabs)[0];
    }

    subTabsContainer.style.marginBottom = "-20px";
    for (let sKey in data.subTabs) {
      const btn = document.createElement("button");
      btn.textContent = data.subTabs[sKey].name;
      btn.style.marginRight = "5px";
      btn.style.cursor = "pointer";

      if (sKey === subKey) {
        btn.style.fontWeight = "bold";
        btn.style.backgroundColor = "#ddd";
      }
      btn.addEventListener("click", function () {
        renderSidebar(groupKey, sKey);
      });
      subTabsContainer.appendChild(btn);
    }

    const subData = data.subTabs[subKey];
    subData.categories.forEach(cat => {
      const catLi = document.createElement("li");
      catLi.textContent = "📁 " + cat.catTitle;
      catLi.style.fontWeight = "bold";
      catLi.style.marginTop = "50px";
      catLi.style.color = "#234";
      catLi.style.listStyle = "none";
      catLi.style.paddingLeft = "0";
      ul.appendChild(catLi);

      cat.sections.forEach(sec => {
        const titleLi = document.createElement("li");
        titleLi.textContent = "📂 " + sec.secTitle;
        titleLi.style.fontWeight = "bold";
        titleLi.style.marginTop = "5px";
        titleLi.style.marginLeft = "20px";
        titleLi.style.color = "#456";
        titleLi.style.listStyle = "none";
        titleLi.style.paddingLeft = "0";
        ul.appendChild(titleLi);

        sec.items.forEach(item => {
          const li = document.createElement("li");
          li.style.marginLeft = "45px";

          const a = document.createElement("a");
          a.href = item.url;
          a.textContent = item.text;

          a.onclick = function (e) {
            e.preventDefault();
            e.stopPropagation();
            window.location.href = item.url;
          };

          li.appendChild(a);
          ul.appendChild(li);
        });
      });
    });

    localStorage.setItem("activeSubGroup", subKey);
  }

  localStorage.setItem("activeGroup", groupKey);
}
